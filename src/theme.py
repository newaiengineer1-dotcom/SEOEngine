def load_theme() -> dict:
    try:
        d = yaml.safe_load(THEME_PATH.read_text(encoding="utf-8")) or {}
    except FileNotFoundError:
        d = {}
    return {**DEFAULT_THEME, **d}


def save_theme(theme: dict) -> None:
    THEME_PATH.write_text(yaml.safe_dump({**DEFAULT_THEME, **theme}, sort_keys=False, allow_unicode=True), encoding="utf-8")


