def css_version(css: str) -> str:
    return hashlib.sha1(css.encode("utf-8")).hexdigest()[:8]


def theme_href(css: str) -> str:
    return f"/{CSS_PATH}?v={css_version(css)}"


def sanitize_css(css: str, max_len: int = 40_000, require_scope: bool = True) -> list[str]:
    """Return a list of problems (empty = safe). Extra (AI/manual) CSS must be scoped under .kg-premium."""
    problems = []
    low = css.lower()
    if len(css) > max_len:
        problems.append("CSS is too large")
    for bad in ("@import", "expression(", "javascript:", "</style", "<script", "-moz-binding"):
        if bad in low:
            problems.append(f"forbidden token: {bad}")
    if re.search(r"(?<![\w-])behavior\s*:", low):
        problems.append("forbidden property: behavior")
    if re.search(r"url\(\s*['\"]?\s*(https?:)?//", low):
        problems.append("external url() is not allowed")
    for m in re.finditer(r"([^{}]+)\{", css if require_scope else ""):
        sel = m.group(1).strip()
        if sel and not sel.startswith("@") and "kg-premium" not in sel and not sel.startswith(("from", "to", ":root", "html")) and not re.fullmatch(r"\d+%", sel):
            problems.append(f'selector not scoped under .kg-premium: "{sel[:60]}"')
    if css.count("{") != css.count("}"):
        problems.append("unbalanced braces")
    return problems


def inventory(html: str) -> dict:
    """What the Designer agent needs to target real selectors on the existing site."""
    soup = soup_of(html)
    classes = Counter(c for t in soup.find_all(True) for c in (t.get("class") or []))
    return {
        "stylesheets": [l.get("href") for l in soup.find_all("link", rel=lambda v: v and "stylesheet" in v) if l.get("href")],
        "top_classes": [c for c, _ in classes.most_common(40)],
        "ids": [t["id"] for t in soup.find_all(id=True)][:40],
        "tags": sorted({t.name for t in soup.find_all(True)} & {"header", "nav", "main", "section", "footer", "form", "button", "table", "ul"}),
        "has_inline_style_attrs": len(soup.find_all(style=True)),
    }


def preview_html(html: str, css: str, base_url: str) -> str:
    """Live-site HTML with the premium CSS applied inline, for a safe preview (nothing is saved)."""
    soup = soup_of(html)
    if soup.head is None or soup.body is None:
        return html
    base = soup.new_tag("base", href=base_url.rstrip("/") + "/")
    soup.head.insert(0, base)
    st = soup.new_tag("style")
    st.string = css
    soup.head.append(st)
    soup.body["class"] = list(soup.body.get("class", [])) + ["kg-premium"]
    return str(soup)


